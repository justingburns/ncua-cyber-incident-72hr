LA = ZoneInfo("America/Los_Angeles")
IID = "CI-20261112-AB12"
HAVE_REPORTLAB = pdf.available()


def run(home, *argv):
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        code = main(["--home", str(home), "--tz", "America/Los_Angeles", "--actor", "tester", *argv],
                    prompt=lambda _: "", interactive=False)
    return code, out.getvalue(), err.getvalue()


def info(data: bytes) -> dict:
    """Read the PDF's document information dictionary."""
    ref = re.search(rb"/Info (\d+) 0 R", data).group(1)
    obj = re.search(rb"\n" + ref + rb" 0 obj\s*<<(.*?)>>\s*endobj", data, re.S).group(1)
    return {k.decode(): v.decode("latin-1") for k, v in re.findall(rb"/(\w+)\s*\(([^)]*)\)", obj)}


def xref_ok(data: bytes) -> bool:
    start = int(re.search(rb"startxref\s+(\d+)", data).group(1))
    lines = data[start:].split(b"\n")
    if lines[0].strip() != b"xref":
        return False
    first, count = map(int, lines[1].split())
    for i in range(1, count):
        offset = int(lines[2 + i][:10])
        if not data[offset:].startswith(b"%d 0 obj" % (first + i)):
            return False
    return True


class Fixture(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.home = Path(self.tmp.name)
        run(self.home, "new", "--id", IID, "--title", "Core provider ransomware",
            "--cu-name", "Example Federal Credit Union", "--charter", "99999",
            "--reporter-name", "Pat Example", "--reporter-title", "CISO",
            "--description", "Core provider reports ransomware.", "--discovered", "2026-11-12 08:15")
        run(self.home, "believe", IID, "--at", "2026-11-12 09:30", "--basis", "Provider confirmed.")

    def tearDown(self):
        self.tmp.cleanup()


@unittest.skipUnless(HAVE_REPORTLAB, "reportlab not installed")
class PDFTests(Fixture):
    def make(self, *extra):
        out = self.home / "packet.pdf"
        code, stdout, _ = run(self.home, "packet", IID, "--format", "pdf", "--out", str(out), *extra)
        self.assertEqual(code, 0)
        return out.read_bytes()

    def test_is_a_valid_pdf(self):
        data = self.make()
        self.assertTrue(data.startswith(b"%PDF-"))
        self.assertTrue(data.rstrip().endswith(b"%%EOF"))
        self.assertTrue(xref_ok(data), "xref offsets must still point at their objects")

    def test_metadata_names_no_software(self):
        data = self.make("--author", "Justin Burns, MBA")
        meta = info(data)
        self.assertEqual(meta["Author"], "Justin Burns, MBA")
        self.assertEqual(meta["Creator"], "")
        self.assertEqual(meta["Producer"], "")
        self.assertEqual(meta["Title"], f"Cyber Incident Record {IID}")
        lowered = data.lower()
        for word in (b"reportlab", b"generated by", b"python", b"ncua72"):
            self.assertNotIn(word, lowered)

    def test_author_defaults_to_reporting_individual(self):
        self.assertEqual(info(self.make())["Author"], "Pat Example")

    def test_default_file_name(self):
        code, out, _ = run(self.home, "packet", IID, "--format", "pdf")
        try:
            self.assertEqual(code, 0)
            self.assertTrue(Path(f"{IID}.pdf").exists())
        finally:
            Path(f"{IID}.pdf").unlink(missing_ok=True)

    def test_dashboard_download(self):
        server = ThreadingHTTPServer(("127.0.0.1", 0), make_handler(self.home, LA))
        threading.Thread(target=server.serve_forever, daemon=True).start()
        base = f"http://127.0.0.1:{server.server_address[1]}"
        try:
            page = urllib.request.urlopen(f"{base}/incident/{IID}").read().decode()
            self.assertIn("Download PDF", page)
            resp = urllib.request.urlopen(f"{base}/incident/{IID}/packet.pdf")
            self.assertEqual(resp.headers["Content-Type"], "application/pdf")
            self.assertIn(f"{IID}.pdf", resp.headers["Content-Disposition"])
            self.assertTrue(resp.read().startswith(b"%PDF-"))
        finally:
            server.shutdown()
            server.server_close()


class MissingLibraryTests(Fixture):
    def test_clear_error_without_reportlab(self):
        with mock.patch.dict(sys.modules, {"reportlab": None}):
            self.assertFalse(pdf.available())
            code, _, err = run(self.home, "packet", IID, "--format", "pdf", "--out", str(self.home / "x.pdf"))
        self.assertEqual(code, 2)
        self.assertIn("pip install reportlab", err)
        self.assertFalse((self.home / "x.pdf").exists())

    def test_other_formats_need_nothing(self):
        with mock.patch.dict(sys.modules, {"reportlab": None}):
            code, out, _ = run(self.home, "packet", IID, "--format", "md")
        self.assertEqual(code, 0)
        self.assertIn("# Cyber Incident Record", out)


